import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
// epub.js distributes a browser-ready IIFE. Copying it avoids the fragile
// source-module resolution path and preserves its global `window.ePub` API.
const jszip = await readFile(require.resolve('jszip/dist/jszip.min.js'), 'utf8');
const epubjs = await readFile(require.resolve('epubjs/dist/epub.min.js'), 'utf8');
const runtime = `${jszip}\n;\n${epubjs}`;
await mkdir('src', { recursive: true });
await writeFile('src/epubRuntime.generated.ts', `// Generated by scripts/build-epub-runtime.mjs. Do not edit.\nexport const epubRuntime = ${JSON.stringify(runtime)};\n`);
